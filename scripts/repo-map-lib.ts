// What `bun run map` writes: an index of the folders, and a map of each folder with one line per source file.
import path from 'node:path';

/** A part of the repository with its folders in the map (`docs/map/<name>/`). */
export type MapArea = { name: string; root: string };

export const MAP_AREAS: MapArea[] = [
  { name: 'core', root: 'packages/core/src' },
  { name: 'web-server', root: 'apps/web/src' },
  { name: 'web-client', root: 'apps/web/client' },
  { name: 'worker', root: 'apps/worker/src' },
  { name: 'scripts', root: 'scripts' },
];

export type SourceFile = { file: string; source: string };

/** One folder of an area (`.` for the area's root) and the map lines of its files. */
type Folder = { area: MapArea; folder: string; entries: string[] };

type AreaFolders = { area: MapArea; folders: Folder[] };

/** Every map file by its path under `docs/map/`, and the folders the summaries miss or name for nothing. */
type Maps = { files: Map<string, string>; undescribed: string[]; unused: string[] };

/** The longest a file's summary may be, so that its map line stays one short line. */
export const MAX_SUMMARY = 120;
const LINT_COMMENT = /^\/\/\s*oxlint-/u;
const GENERATED = 'Generated by `bun run map`; do not edit. Tests are left out.';
const INTRO =
  "Find the folder of what you change below, then read its map: one line per file, from the file's top `//` comment. To find a word in every map: `grep -rn <word> docs/map`.";

function clean(lines: string[]): string {
  return lines
    .map((line) => line.replace(/^\s*\/\/\s?/u, ''))
    .join(' ')
    .replaceAll(/\s+/gu, ' ')
    .trim();
}

/** Up to the first `.`, `!` or `?` ending a sentence, not counting those in a `code` span. */
const FIRST_SENTENCE = /^(?:`[^`]*`|[^`.!?]|[.!?](?!\s|$)|`)*[.!?]?/u;

function firstSentence(text: string): string {
  return FIRST_SENTENCE.exec(text)?.[0] ?? text;
}

/** The `//` lines at the top of the file, before any code; null when it starts otherwise. */
function headerComment(lines: string[]): string[] | null {
  const start = lines.findIndex((line) => line.trim() !== '' && !LINT_COMMENT.test(line.trim()));
  if (!(lines[start]?.trim().startsWith('//') ?? false)) {
    return null;
  }
  const end = lines.findIndex((line, at) => at > start && !line.trim().startsWith('//'));
  return lines.slice(start, end === -1 ? undefined : end);
}

/** A file's summary: the first sentence of its top `//` comment, whole; null without one. */
export function summaryOf(source: string): string | null {
  const comment = headerComment(source.split('\n'));
  const text = comment ? clean(comment) : '';
  return text === '' ? null : firstSentence(text);
}

/** A folder's key in the folder summaries: `<area>` for the area's root, else `<area>/<folder>`. */
function folderKey({ area, folder }: Folder): string {
  return folder === '.' ? area.name : `${area.name}/${folder}`;
}

/** Where a folder's map goes, relative to `docs/map/`. */
function folderMapPath({ area, folder }: Folder): string {
  return `${area.name}/${folder === '.' ? 'root' : folder.replaceAll('/', '-')}.md`;
}

function rootFirst(a: string, b: string): number {
  return Number(b === '.') - Number(a === '.') || a.localeCompare(b);
}

/** The area's folders, its root first, then by name, each with its files' lines sorted. */
function foldersOf(area: MapArea, files: SourceFile[]): Folder[] {
  const folders = new Map<string, string[]>();
  for (const { file, source } of files.toSorted((a, b) => a.file.localeCompare(b.file))) {
    const relative = path.posix.relative(area.root, file);
    const folder = path.posix.dirname(relative);
    const entry = `- \`${path.posix.basename(relative)}\`: ${summaryOf(source) ?? '(no summary)'}`;
    folders.set(folder, [...(folders.get(folder) ?? []), entry]);
  }
  return [...folders]
    .toSorted(([a], [b]) => rootFirst(a, b))
    .map(([folder, entries]) => ({ area, folder, entries }));
}

function renderFolderMap(folder: Folder, summary: string): string {
  const where = path.posix.join(folder.area.root, folder.folder);
  const header = `# Map: \`${where}/\`\n\n${summary}\n\n${GENERATED} All folders: [the index](../README.md).`;
  return `${header}\n\n${folder.entries.join('\n')}\n`;
}

function indexLine(folder: Folder, summary: string): string {
  const count = folder.entries.length;
  const label = folder.folder === '.' ? './' : `${folder.folder}/`;
  return `- [\`${label}\`](${folderMapPath(folder)}), ${count} file${count === 1 ? '' : 's'}: ${summary}`;
}

function renderIndex(areas: AreaFolders[], summary: (folder: Folder) => string): string {
  const sections = areas.map(({ area, folders }) => {
    const lines = folders.map((folder) => indexLine(folder, summary(folder)));
    return `## ${area.name}: \`${area.root}\`\n\n${lines.join('\n')}\n`;
  });
  return `# Map of the repository\n\n${INTRO}\n\n${GENERATED}\n\n${sections.join('\n')}`;
}

/** The index and every folder's map, from each area's files and the folder summaries. */
export function renderMaps(
  areas: { area: MapArea; files: SourceFile[] }[],
  summaries: Record<string, string>,
): Maps {
  const withFolders = areas.map(({ area, files }) => ({ area, folders: foldersOf(area, files) }));
  const all = withFolders.flatMap(({ folders }) => folders);
  const keys = new Set(all.map((folder) => folderKey(folder)));
  const summary = (folder: Folder): string => summaries[folderKey(folder)] ?? '(no summary)';
  const files = new Map([['README.md', renderIndex(withFolders, summary)]]);
  for (const folder of all) {
    files.set(folderMapPath(folder), renderFolderMap(folder, summary(folder)));
  }
  return {
    files,
    undescribed: [...keys].filter((key) => summaries[key] === undefined),
    unused: Object.keys(summaries).filter((key) => !keys.has(key)),
  };
}
